"""Generate _nrl_rules.py (Python) and native/nrl_rules.inc (C) from Wasser's english.c.

Usage: python gen_nrl_rules.py <path to english.c>
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tools", "reference", "_nrl_rules.py")
OUT_C = os.path.join(ROOT, "native", "nrl_rules.inc")
NAMES = {"Anything": "", "Nothing": " ", "Pause": " ", "Silent": ""}
ITEM = r'(Anything|Nothing|Pause|Silent|"(?:[^"\\]|\\.)*")'
RULE = re.compile(r"\{\s*%s\s*,\s*(0|%s)\s*,\s*%s\s*,\s*%s\s*\}" % (ITEM, ITEM, ITEM, ITEM))


def value(tok):
    if tok in NAMES:
        return NAMES[tok]
    return tok[1:-1].replace('\\"', '"').replace("\\\\", "\\")


def main(src):
    text = open(src, encoding="latin-1").read()
    tables = {}
    for m in re.finditer(r"static Rule (\w+)_rules\[\] =\s*\{(.*?)\n\t\};", text, re.S):
        key = "" if m.group(1) == "punct" else m.group(1)
        rules = []
        for r in RULE.finditer(m.group(2)):
            if r.group(2) == "0":
                continue
            rules.append(tuple(value(r.group(i)) for i in (1, 2, 4, 5)))
        tables[key] = rules
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write('"""NRL Report 7948 letter-to-sound rules (US Government work), as transcribed\n'
                'in John A. Wasser\'s public-domain english.c. Generated by tools/gen_nrl_rules.py."""\n\n')
        f.write("RULES = {\n")
        for key in sorted(tables):
            f.write("    %r: [\n" % key)
            for rule in tables[key]:
                f.write("        %r,\n" % (rule,))
            f.write("    ],\n")
        f.write("}\n")
    with open(OUT_C, "w", encoding="ascii", newline="\n") as f:
        f.write("/* NRL Report 7948 letter-to-sound rules (US Government work), as transcribed\n"
                " * in John A. Wasser's public-domain english.c. Generated by\n"
                " * tools/gen_nrl_rules.py -- do not edit. */\n\n")
        names = []
        for key in [""] + [chr(c) for c in range(ord("A"), ord("Z") + 1)]:
            name = "nrl_" + (key or "punct")
            names.append(name)
            f.write("static const NrlRule %s[] = {\n" % name)
            for rule in tables.get(key, []):
                f.write("\t{%s},\n" % ", ".join(c_str(x) for x in rule))
            f.write("\t{0, 0, 0, 0}\n};\n\n")
        f.write("static const NrlRule *const nrl_tables[27] = {\n\t%s\n};\n" % ", ".join(names))
    print(OUT, "and", OUT_C, sum(len(v) for v in tables.values()), "rules in", len(tables), "tables")


def c_str(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


if __name__ == "__main__":
    main(sys.argv[1])
